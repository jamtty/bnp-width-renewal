-- ============================================================
-- 전문가 관리 테이블 (자문위원/수퍼바이저, 전문상담사/코치)
-- ============================================================

CREATE TABLE IF NOT EXISTS expert_tbl (
  expert_id    INT          NOT NULL AUTO_INCREMENT COMMENT '전문가 고유번호',
  expert_type  VARCHAR(20)  NOT NULL DEFAULT 'advisor' COMMENT '구분 (advisor: 자문위원/수퍼바이저, coach: 전문상담사/코치)',
  expert_name  VARCHAR(100) NOT NULL                COMMENT '이름',
  expert_tags  VARCHAR(500) NULL                    COMMENT '태그 (예: #불안 #트라우마)',
  expert_desc  VARCHAR(500) NULL                    COMMENT '한줄 소개',
  expert_career TEXT        NULL                    COMMENT '경력/약력 (줄바꿈 구분)',
  expert_img   VARCHAR(500) NULL                    COMMENT '프로필 이미지 (저장 파일명)',
  expert_img_org VARCHAR(500) NULL                  COMMENT '프로필 이미지 (원본 파일명)',
  sort_order   INT         NOT NULL DEFAULT 1       COMMENT '정렬순서',
  use_yn       CHAR(1)     NOT NULL DEFAULT 'Y'     COMMENT '사용여부',
  del_yn       CHAR(1)     NOT NULL DEFAULT 'N'     COMMENT '삭제여부',
  created_at   DATETIME    NULL DEFAULT NOW()       COMMENT '등록일시',
  updated_at   DATETIME    NULL                     COMMENT '수정일시',
  PRIMARY KEY (expert_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='전문가 관리';

